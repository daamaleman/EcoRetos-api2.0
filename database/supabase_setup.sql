-- ---------------------------------------------------------------------
-- 1. TABLAS (mismos nombres que las entidades JPA del API)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS Usuarios (
    IdUsuario            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CIF                  VARCHAR(20)  NOT NULL UNIQUE,
    NombreCompleto       VARCHAR(150) NOT NULL,
    CorreoInstitucional  VARCHAR(150),
    ContrasenaHash       VARCHAR(255) NOT NULL,
    Rol                  VARCHAR(20)  NOT NULL,          -- ESTUDIANTE | ADMINISTRADOR
    Activo               BOOLEAN      NOT NULL DEFAULT TRUE,
    PuntosTotales        INTEGER      NOT NULL DEFAULT 0,
    FechaCreacion        TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS Retos (
    IdReto          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Titulo          VARCHAR(120) NOT NULL,
    Descripcion     VARCHAR(300) NOT NULL,
    Puntos          INTEGER      NOT NULL,
    Dificultad      VARCHAR(20)  NOT NULL,               -- FACIL | MEDIA | ALTA
    TipoValidacion  VARCHAR(20)  NOT NULL,               -- MANUAL | IA_APOYO | HIBRIDA
    Activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    FechaCreacion   TIMESTAMP(6) NOT NULL,
    FechaInicio     TIMESTAMP(6),
    FechaFin        TIMESTAMP(6),
    DuracionHoras   INTEGER,
    CreadoPor       INTEGER      NOT NULL REFERENCES Usuarios(IdUsuario)
);

CREATE TABLE IF NOT EXISTS Participaciones (
    IdParticipacion   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IdUsuario         INTEGER      NOT NULL REFERENCES Usuarios(IdUsuario),
    IdReto            INTEGER      NOT NULL REFERENCES Retos(IdReto),
    FechaAceptacion   TIMESTAMP(6) NOT NULL,
    Estado            VARCHAR(20)  NOT NULL,             -- ACEPTADO | ENVIADO | APROBADO | RECHAZADO
    FechaResolucion   TIMESTAMP(6),
    ObservacionAdmin  VARCHAR(300),
    FechaAprobacion   TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS Evidencias (
    IdEvidencia          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IdParticipacion      INTEGER       NOT NULL REFERENCES Participaciones(IdParticipacion),
    UrlImagen            VARCHAR(500)  NOT NULL,
    FechaSubida          TIMESTAMP(6)  NOT NULL,
    EstadoValidacion     VARCHAR(20)   NOT NULL,         -- PENDIENTE | APROBADO | RECHAZADO
    ResultadoIA          VARCHAR(50),
    ConfianzaIA          NUMERIC(38,2),
    EtiquetasDetectadas  VARCHAR(300),
    ObservacionAdmin     VARCHAR(300)
);

CREATE TABLE IF NOT EXISTS Insignias (
    IdInsignia     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre         VARCHAR(100) NOT NULL,
    Descripcion    VARCHAR(250) NOT NULL,
    PuntosMinimos  INTEGER      NOT NULL,
    IconoUrl       VARCHAR(500),
    Activa         BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS UsuarioInsignias (
    IdUsuarioInsignia  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IdUsuario          INTEGER      NOT NULL REFERENCES Usuarios(IdUsuario),
    IdInsignia         INTEGER      NOT NULL REFERENCES Insignias(IdInsignia),
    FechaAsignacion    TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS RetosPropuestos (
    IdPropuesta       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IdUsuario         INTEGER      NOT NULL REFERENCES Usuarios(IdUsuario),
    Titulo            VARCHAR(120) NOT NULL,
    Descripcion       VARCHAR(300) NOT NULL,
    Categoria         VARCHAR(80)  NOT NULL,
    Estado            VARCHAR(20)  NOT NULL,             -- PENDIENTE | APROBADA | RECHAZADA
    FechaPropuesta    TIMESTAMP(6) NOT NULL,
    ObservacionAdmin  VARCHAR(300)
);

-- El API se conecta con el usuario "postgres", así que no hace falta abrir
-- estas tablas al público. Activar RLS sin políticas bloquea el acceso
-- desde la API pública de Supabase (anon key), pero no al API de Spring Boot.
ALTER TABLE Usuarios         ENABLE ROW LEVEL SECURITY;
ALTER TABLE Retos            ENABLE ROW LEVEL SECURITY;
ALTER TABLE Participaciones  ENABLE ROW LEVEL SECURITY;
ALTER TABLE Evidencias       ENABLE ROW LEVEL SECURITY;
ALTER TABLE Insignias        ENABLE ROW LEVEL SECURITY;
ALTER TABLE UsuarioInsignias ENABLE ROW LEVEL SECURITY;
ALTER TABLE RetosPropuestos  ENABLE ROW LEVEL SECURITY;

